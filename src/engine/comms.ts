/**
 * Telemetry, Tracking, and Command (TT&C) + Science Downlink communications module.
 *
 * Implements:
 * - Daily science data volume generation (GB/day):
 *     data/day = sum(rate_Mbps * duty * 86400) / 8 / 1000
 * - Onboard solid-state recorder (SSR) buffer capacity & overflow check
 * - Daily downlink volume (GB/day):
 *     downlink/day = rate_Mbps * (contact_seconds / day) * efficiency 0.80 / 8 / 1000
 * - Data return fraction: min(1, downlink / produced)
 * - Ground station network models (Dedicated 1 site, Commercial 4-8 sites, DSN/NSN deep-space)
 */

export interface GroundNetworkSpec {
  id: string;
  name: string;
  type: "dedicated" | "commercial" | "dsn-nsn";
  stationCount: number;
  contactMinutesPerDayLEO: number;
  continuousGEO: boolean;
  costPerPassM: number;
  annualOpsCostM: number;
  deepSpaceSupport: boolean;
  referenceDistanceKm: number;
}

export interface CommsSpec {
  id: string;
  name: string;
  band: "S-band" | "X-band" | "Ka-band" | "optical-laser";
  downlinkRateMbps: number;
  rfPowerW: number;
  dcPowerW: number;
  massKg: number;
  costM: number;
  trl: number;
  isDeepSpaceHGA: boolean;
}

export interface CommsEvaluation {
  dataGeneratedGbPerDay: number;
  downlinkCapacityGbPerDay: number;
  dataReturnFraction: number;
  dailyContactMinutes: number;
  storageRequiredGb: number;
  storageInstalledGb: number;
  storageBufferDays: number;
  storageOverflowRisk: boolean;
  commsSubsystemMassKg: number;
  commsPowerW: number;
  groundNetworkCostM: number;
}

/**
 * Computes daily data generated by instruments in Gigabytes (10^9 bytes) per day.
 */
export function computeDailyDataGeneratedGb(
  instruments: Array<{ dataRateMbps: number; dutyCycle: number }>
): number {
  let totalBitsPerDay = 0;
  for (const inst of instruments) {
    totalBitsPerDay += inst.dataRateMbps * 1e6 * inst.dutyCycle * 86400;
  }
  // Convert bits to GB (8 bits / byte, 1e9 bytes / GB)
  return totalBitsPerDay / (8 * 1e9);
}

/**
 * Computes downlink volume in GB per day given contact duration and comms bandwidth.
 */
export function computeDownlinkCapacityGb(
  downlinkRateMbps: number,
  contactMinutesPerDay: number,
  efficiency = 0.8 // 80% protocol and packet framing efficiency
): number {
  if (downlinkRateMbps <= 0 || contactMinutesPerDay <= 0) return 0;
  const contactSeconds = contactMinutesPerDay * 60;
  const usableBits = downlinkRateMbps * 1e6 * contactSeconds * efficiency;
  return usableBits / (8 * 1e9);
}

/**
 * Computes effective contact minutes per day for an orbit and ground network.
 */
export function computeEffectiveContactMinutes(
  orbitType:
    | "LEO"
    | "SSO"
    | "MEO"
    | "GEO"
    | "HEO"
    | "L1"
    | "L2"
    | "LUNAR"
    | "SURFACE"
    | "MARS"
    | "JUPITER"
    | "VENUS"
    | "TITAN"
    | "ASTEROID",
  passesPerDayPerStation: number,
  meanPassDurationSeconds: number,
  network: GroundNetworkSpec,
  distanceFromEarthKm = 0
): number {
  if (orbitType === "GEO") {
    // GEO has continuous line-of-sight to an assigned longitude station
    return 1440; // 24 hours * 60 min
  }

  if (
    orbitType === "L1" ||
    orbitType === "L2" ||
    orbitType === "LUNAR" ||
    orbitType === "SURFACE" ||
    orbitType === "MARS" ||
    orbitType === "JUPITER" ||
    orbitType === "VENUS" ||
    orbitType === "TITAN" ||
    orbitType === "ASTEROID"
  ) {
    // Deep space missions rely on scheduled tracking passes via DSN / NSN
    if (!network.deepSpaceSupport) {
      return 0; // standard commercial LEO ground stations cannot track lunar/planetary distances
    }
    // Typically 4 to 8 hours of scheduled track per day
    return 360; // 6 hours average
  }

  if (orbitType === "HEO") {
    // Highly elliptical orbit: extended contact during apogee dwelling (e.g. 10-12 hours per orbit)
    return 480;
  }

  // LEO / SSO orbits: pass geometry scaled by number of stations in network
  const singleStationDailyMinutes = (passesPerDayPerStation * meanPassDurationSeconds) / 60;
  // Account for non-overlapping station passes with sub-linear multi-station factor
  const stationMultiplier = Math.pow(network.stationCount, 0.75);
  return singleStationDailyMinutes * stationMultiplier;
}

/**
 * Full comms evaluation.
 */
export function evaluateComms(
  instruments: Array<{ dataRateMbps: number; dutyCycle: number }>,
  commsHardware: CommsSpec,
  network: GroundNetworkSpec,
  storageGbInstalled: number,
  contactMinutesPerDay: number,
  missionYears: number
): CommsEvaluation {
  const dataGeneratedGbPerDay = computeDailyDataGeneratedGb(instruments);
  const downlinkCapacityGbPerDay = computeDownlinkCapacityGb(
    commsHardware.downlinkRateMbps,
    contactMinutesPerDay,
    0.8
  );

  const dataReturnFraction =
    dataGeneratedGbPerDay > 0
      ? Math.min(1.0, downlinkCapacityGbPerDay / dataGeneratedGbPerDay)
      : 1.0;

  // Minimum recommended storage is at least 1.5 days of generated data to buffer missed passes
  const storageRequiredGb = Math.max(10, dataGeneratedGbPerDay * 1.5);
  const storageBufferDays =
    dataGeneratedGbPerDay > 0 ? storageGbInstalled / dataGeneratedGbPerDay : 999;
  const storageOverflowRisk = storageGbInstalled < storageRequiredGb;

  const groundNetworkCostM =
    network.annualOpsCostM * missionYears +
    (network.type === "commercial" && !network.continuousGEO
      ? Math.min(16, contactMinutesPerDay / 10) * (365 * missionYears) * network.costPerPassM
      : 0);

  return {
    dataGeneratedGbPerDay,
    downlinkCapacityGbPerDay,
    dataReturnFraction,
    dailyContactMinutes: contactMinutesPerDay,
    storageRequiredGb,
    storageInstalledGb: storageGbInstalled,
    storageBufferDays,
    storageOverflowRisk,
    commsSubsystemMassKg: commsHardware.massKg,
    commsPowerW: commsHardware.dcPowerW,
    groundNetworkCostM,
  };
}
